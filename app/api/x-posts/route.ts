import { NextRequest, NextResponse } from 'next/server'
import { GoogleGenerativeAI } from '@google/generative-ai'
import type { XPostResult } from '@/types'

const genAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY!)

export async function POST(req: NextRequest) {
  const { news, style_samples, author_profile } = await req.json()

  if (!news || typeof news !== 'string' || news.trim().length === 0) {
    return NextResponse.json({ error: 'ニュース本文を入力してください' }, { status: 400 })
  }

  const samples = typeof style_samples === 'string' ? style_samples.trim() : ''
  const profile = typeof author_profile === 'string' ? author_profile.trim() : ''

  // responseMimeType でJSON出力を強制し、parse失敗を減らす（無償）。
  // temperatureを上げて蝶番の発想を発散させ、横並びの浅い候補を避ける。
  const model = genAI.getGenerativeModel({
    model: 'gemini-1.5-flash',
    generationConfig: { responseMimeType: 'application/json', temperature: 0.95 },
  })

  // 過去投稿が渡されたら、文体と視点の癖の見本として先頭に置く。
  // これが「私の文章に近い」かつ「私らしい深さ」を生む唯一の手段。
  const styleSection = samples
    ? `# あなた（書き手）の過去投稿（最優先で再現する見本）
以下はこのアカウントの実際の投稿です。次の2点を抽出し、全候補に反映せよ。
1. 文体: 語彙・一人称・語尾・文の長さとリズム・改行や記号の使い方・絵文字の有無。一般的な解説文ではなく、この人が書いたと分かる文章にする。
2. 視点の癖: この人が物事を見るときの典型的な切り口・価値観・こだわり。蝶番(hinge)の選び方自体を、この人ならどこを突くかに寄せる。
※真似るのは「文体と視点」であり、過去投稿の話題やフレーズをそのまま流用しない。

----- 過去投稿ここから -----
${samples}
----- 過去投稿ここまで -----

`
    : ''

  // 書き手の経歴は「視座」の源泉。他人が持てない立場から蝶番を選ばせ、深さを出す。
  const profileSection = profile
    ? `# あなた（書き手）の経歴・立場
${profile}
この書き手の強みはジェネラリストであること。面白さは一つの専門で語ることではなく、
離れた領域どうしを予想外につなぐところにある。
蝶番(hinge)を選ぶときは、ニュースの分野とは別の引き出しの原理を持ち込んで橋を架けよ。
（例: 経済の話を育成やチーム作りの原理で読む、国内の常識を途上国の常識で相対化する、など。）
一つの視点だけに寄せて語らない。ただしこじつけは禁止。橋が自然に成立する角度だけを選ぶ。
肩書きは羅列せず、視点として滲ませる。
切り口に使う引き出しは職歴・経験（仕事や住んでいた場所など）に限る。
趣味や個人的な嗜好は人柄の彩りにすぎないので、ニュースの切り口（蝶番）に無理に持ち込まない。

`
    : ''

  // 深さの本体はこのプロンプト。ニュースの表面をなぞらず、本質を一段抽象化し、
  // 別の場（経営・人・生き方）へ転用して「自分の考え」を立ち上げる抽象化パイプライン。
  const prompt = `あなたはニュースを入口に、書き手自身の「考え」を立ち上げてX（旧Twitter）の投稿候補を作る編集者です。
最も避けるべき失敗は「ニュースの表面をなぞった簡易的な解釈・感想」です。それは退屈で価値がありません。
価値は、表面の出来事から本質（構造・原理）を抜き出し、それを別の場へ転用して、読者の物の見方を一つ変えることにあります。

${profileSection}${styleSection}# 入力ニュースについて
ニュースの分野は問わない（経済・スポーツ・娯楽・社会・事件、何でもよい）。
価値は分野ではなく、表面の出来事から本質を抽象化し、それを別の場——特に経営・組織・人・生き方——へ
転用するところから生まれる。スポーツや娯楽の話こそ、構造を抽象化すれば経営や人生に効く投稿になる。
分野そのものへの感想で終わらせない。

# 書き手の思考様式
- 論点を疑う：ニュースが差し出す「正面の問い」は仮の論点。現象／課題／論点を切り分け、真に解くべき論点を選び直す。
- 仮説を先に置く・発想を揺らす：反対側・両極端・ゼロベースの3方向で振ってから選ぶ。外れてよい、賭けに価値。
- 具体⇄抽象を往復：表面の具体を一段抽象化して構造（本質）を掴み、別の具体に戻す。具体例で語れない抽象論は出さない。
- アナロジーは構造で：離れた領域は「構造の共通性」でつなぐ。表面類似のこじつけは禁止。
- So What?：「で、そこから何を考えるか」に必ず答える。言い換え・説明で止まらない。

# 思考の手順（必ずこの順で。表面をなぞらない）
1. 具体→本質：ニュースの枝葉を捨て、「これは構造的に何の話か」を一文で抽象化する。
   分野固有の言葉（選手名・社名・競技名・固有の事件名）を使わずに言えるレベルまで上げる。
   ここで止まると「ニュースの感想」になる。必ず次へ進む。
2. 本質→転用：その構造・原理が効く別の場を一つ選ぶ。経営・組織・人・生き方、または別ジャンル。
   つなぐ根拠は「構造の共通性」であること。
3. 転用→考え：その転用から、書き手自身の「考え」を一つ立ち上げる。単なる解釈・説明ではなく、
   主張・問い・予測のいずれか。外れうる賭けになっていること。これが投稿の主役で、ニュースは入口。
4. 本質の取り方が異なる3通りの候補を作る。
また全体を通して、このニュースが投げかける本質的な問いを core_question として一文で書く。

# 例（スポーツ→経営の抽象化。これくらい平面を変える）
ニュース:「低反発バット導入で、従来の強豪校が苦戦している」
1. 本質: 環境（ルール）が変わると、過去に最適化した強みが一夜で負債に変わる、という構造。
2. 転用: 企業も同じ。今の勝ちパターンに最適化しきった組織ほど、環境変化に脆い。
3. 考え:「"確立した勝ちパターンがある"ことは、ルール変更前夜では最大のリスクかもしれない。強さの中身が"適応力"か"過去への最適化"かを見極めたい。」

# 各候補が満たすこと
- essence: 本質。一段抽象化した構造・原理を一文で。分野固有語を使わない（使っていたら抽象化不足）。
- transfer: その原理が効く別の場（経営/組織/人/生き方/別ジャンル）。構造の共通性で。3候補で重複させない。
- thought: そこから立ち上げた書き手の「考え」＝主張・問い・予測。外れうる賭け。これが投稿の核。
- hook: 1行目。結論ファーストで、thoughtの核を単独で成立する形で前に出す。ニュース説明から始めない。
- post: X投稿本文。140字以内。必ずhookで始める。主役はthoughtで、ニュースは入口として最小限だけ触れる。読者が後で確認できる具体や、可能なら数字を一つ。背景説明で字数を埋めない。
- self_check: 「ニュースの表面をなぞった感想になっていないか」「essenceは分野語なしで言えているか」「thoughtは賭けになっているか」を自己診断。だめなら作り直す。

# 禁止事項
- ニュースの表面をなぞる／要約／簡易な感想で終わる（本質抽象化と考えの立ち上げが無い）。これが最悪。
- essenceが分野固有語のまま（抽象化できていない）。
- thoughtが「重要だ」「注目」「考えさせられる」など賭けになっていない無情報。
- 構造が一致しないアナロジーのこじつけ。具体例で支えられない抽象論。

# トレンド乗り返信ドラフト（trend_replies）
上記の投稿候補とは別に、このニュースが伸びている時に「他人の人気投稿」へ返信または引用で
被せて使えるドラフトを2つ作る。狙いは、自分のフォロワー外に届かせること。
- 相手の具体的な投稿文は不明な前提で、このニュースについての価値追加コメント単体として成立させる。
- 賛同・要約で終わらせず、本質を抽象化して別の場へ転用した角度を一つ足す。
- 140字以内。1行目で刺す。媚び・定型句（「勉強になります」等）は禁止。
- angle=使った視座、reply=本文、note=どんな投稿に被せると刺さるか（被せ先の例）。

# 出力形式
JSONのみを返す。前後に説明文・コードフェンス・余計な文字を一切付けない。
{
  "core_question": "...",
  "candidates": [
    { "essence": "...", "transfer": "...", "thought": "...", "hook": "...", "post": "...", "self_check": "..." }
  ],
  "trend_replies": [
    { "angle": "...", "reply": "...", "note": "..." }
  ]
}

# 対象ニュース
${news}`

  try {
    const result = await model.generateContent(prompt)
    const text = result.response.text().trim()
    const jsonMatch = text.match(/\{[\s\S]*\}/)
    if (!jsonMatch) {
      return NextResponse.json({ error: 'AI応答の解析に失敗しました' }, { status: 500 })
    }
    const parsed: XPostResult = JSON.parse(jsonMatch[0])
    return NextResponse.json(parsed)
  } catch {
    return NextResponse.json({ error: 'X投稿候補の生成に失敗しました' }, { status: 500 })
  }
}
